#!/usr/bin/env node
/**
 * Builds the API route manifest the server-route sweep runs over.
 *
 * It walks apps/web/app/api/**\/route.ts, reads which HTTP verbs each route handler exports, and
 * writes apps/web/playwright/suites/api/routes.generated.ts. Re-run it whenever a route is added,
 * removed, or changes its verbs:
 *
 *   node apps/web/playwright/scripts/collect-api-routes.mjs
 *
 * A route handler that exports no verb is reported instead of being silently skipped.
 */
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webApp = resolve(here, '../..');
const apiRoot = resolve(webApp, 'app/api');
const outputFile = resolve(here, '../suites/api/routes.generated.ts');

const VERBS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'];
/** Next.js special files that are not HTTP handlers. */
const SKIP = new Set(['route.tsx', 'route.jsx', 'route.js']);

function walk(dir) {
	const found = [];
	for (const entry of readdirSync(dir)) {
		const full = resolve(dir, entry);
		if (statSync(full).isDirectory()) found.push(...walk(full));
		else if (full.endsWith('route.ts') && !SKIP.has(entry)) found.push(full);
	}
	return found.sort();
}

/** `/app/api/auth/login/route.ts` -> `/api/auth/login`, keeping Next's dynamic segments as written. */
function routeUrl(file) {
	const rel = relative(apiRoot, file).replace(/\\/g, '/').replace(/\/route\.ts$/, '');
	return `/api/${rel}`;
}

function verbsOf(source) {
	const verbs = new Set();
	for (const verb of VERBS) {
		const pattern = new RegExp(`export\\s+(async\\s+)?function\\s+${verb}\\b|export\\s+const\\s+${verb}\\b|export\\s+{[^}]*\\b${verb}\\b`, 'm');
		if (pattern.test(source)) verbs.add(verb);
	}
	// A dynamic `export const GET = handler` style route (route handlers using a shared function).
	if (/export\s+default\s+/.test(source)) verbs.add('GET');
	return [...verbs];
}

const routes = [];
const noVerbs = [];
for (const file of walk(apiRoot)) {
	const verbs = verbsOf(readFileSync(file, 'utf8'));
	if (verbs.length === 0) {
		noVerbs.push(routeUrl(file));
		continue;
	}
	routes.push({ path: routeUrl(file), verbs });
}

const body = `// GENERATED by apps/web/playwright/scripts/collect-api-routes.mjs — do not hand-edit.
// Regenerate with: node apps/web/playwright/scripts/collect-api-routes.mjs
//
// Every Next.js route handler in apps/web/app/api, with the HTTP verbs it exports. The sweep in
// suites/api/sweep.spec.ts calls each one and asserts the server answers as JSON without a 5xx.

export type ApiRoute = { path: string; verbs: string[] };

export const apiRoutes: ApiRoute[] = ${JSON.stringify(routes, null, 1)};

/** Route handlers found with no recognizable verb export: worth a look, not worth guessing at. */
export const unattributedApiRoutes: string[] = ${JSON.stringify(noVerbs, null, 1)};
`;

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, body, 'utf8');
console.log(`routes: ${routes.length}, without verb exports: ${noVerbs.length}`);
console.log(`wrote ${relative(process.cwd(), outputFile)}`);
if (noVerbs.length) console.log(noVerbs.join('\n'));
