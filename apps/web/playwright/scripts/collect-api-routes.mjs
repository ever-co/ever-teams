#!/usr/bin/env node
/**
 * Builds the API route manifest the server-route sweep runs over.
 *
 * It walks apps/web/app/api/**\/route.ts, reads which HTTP verbs each route handler exports, and
 * writes apps/web/playwright/suites/api/routes.generated.ts. Re-run it whenever a route is added,
 * removed, or changes its verbs:
 *
 *   node apps/web/playwright/scripts/collect-api-routes.mjs
 *
 * A handler with no recognizable verb export is reported instead of being skipped silently.
 *
 * `--check` writes nothing and exits 1 when the checked-in manifest is out of date
 * (suites/api/manifests.spec.ts runs it that way).
 */
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { collectApiRoutes, writeGenerated } from './api-routes-lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const apiRoot = resolve(here, '../../app/api');
const outputFile = resolve(here, '../suites/api/routes.generated.ts');

const { routes, unattributed } = collectApiRoutes(apiRoot);

const body = `// GENERATED by apps/web/playwright/scripts/collect-api-routes.mjs — do not hand-edit.
// Regenerate with: node apps/web/playwright/scripts/collect-api-routes.mjs
//
// Every Next.js route handler in apps/web/app/api, with the HTTP verbs it exports. The sweeps in
// suites/api/ call each one and assert the server answers as an API without an unhandled 5xx.

export type ApiRoute = { path: string; verbs: string[] };

export const apiRoutes: ApiRoute[] = ${JSON.stringify(routes, null, 1)};

/** Route handlers the collector could not attribute a verb to: worth a look, not worth guessing at. */
export const unattributedApiRoutes: string[] = ${JSON.stringify(unattributed, null, 1)};
`;

if (await writeGenerated(outputFile, body, 'node apps/web/playwright/scripts/collect-api-routes.mjs')) {
	console.log(`routes: ${routes.length}, without verb exports: ${unattributed.length}`);
	console.log(`wrote ${relative(process.cwd(), outputFile)}`);
	if (unattributed.length) console.log(unattributed.join('\n'));
}
