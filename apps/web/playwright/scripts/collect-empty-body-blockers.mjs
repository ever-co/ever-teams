#!/usr/bin/env node
/**
 * Rebuilds the pinned list of route handlers that answer 5xx to a mutating request with no body.
 *
 * It reads the JSON report the API suite already writes (artifacts/playwright-api.json) and turns
 * every failed "with no body" test into an entry carrying the status that test saw. The suite then
 * asserts each pinned status exactly, so the list is evidence from a real run and a handler that
 * changes behaviour fails instead of sliding into the list unnoticed.
 *
 *   yarn playwright test --config apps/web/playwright/playwright.api.config.ts
 *   node apps/web/playwright/scripts/collect-empty-body-blockers.mjs
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { collectApiRoutes, writeGenerated } from './api-routes-lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
// A reporter's outputFile is resolved against the config's own folder, so that is where the report is.
const reportFile = resolve(here, '../artifacts/playwright-api.json');
const outputFile = resolve(here, '../suites/api/empty-body-blockers.generated.ts');

if (!existsSync(reportFile)) {
	console.error(`no report at ${reportFile}. Run the API suite first:`);
	console.error('  yarn playwright test --config apps/web/playwright/playwright.api.config.ts');
	process.exit(1);
}

const report = JSON.parse(readFileSync(reportFile, 'utf8'));

/** Playwright nests suites; collect { title, status, errors } for every test. */
function collectTests(suites, acc) {
	for (const suite of suites ?? []) {
		for (const spec of suite.specs ?? []) {
			for (const testcase of spec.tests ?? []) {
				const result = testcase.results?.[testcase.results.length - 1];
				const annotations = [...(result?.annotations ?? []), ...(testcase.annotations ?? [])];
				const observed = annotations.find((annotation) => annotation.type === 'observed-status');
				acc.push({ title: spec.title, observedStatus: observed ? Number(observed.description) : undefined });
			}
		}
		collectTests(suite.suites, acc);
	}
	return acc;
}

/** Every bodiless case empty-body.spec.ts runs: the mutating verbs of every handler (the spec's MUTATING list). */
const MUTATING = ['POST', 'PUT', 'PATCH'];
const expected = new Set(
	collectApiRoutes(resolve(here, '../../app/api')).routes.flatMap((route) =>
		route.verbs.filter((verb) => MUTATING.includes(verb)).map((verb) => `${verb} ${route.path}`)
	)
);

const blockers = {};
const observed = new Set();
for (const testcase of collectTests(report.suites, [])) {
	if (!testcase.title.includes('with no body')) continue;
	// Titles look like: "POST /api/tags with no body answers a 4xx, not a 5xx"
	const match = testcase.title.match(/^(GET|POST|PUT|PATCH|DELETE) (\S+) with no body/);
	if (!match) continue;
	const title = `${match[1]} ${match[2]}`;
	if (testcase.observedStatus !== undefined) observed.add(title);
	// The status the handler actually answered, recorded by the spec whether the case passed or failed: a pinned
	// handler that still answers its 5xx passes, and must keep its entry.
	if (testcase.observedStatus === undefined || testcase.observedStatus < 500) continue;
	blockers[title] = {
		status: testcase.observedStatus,
		detail: `${title} with no body crashed the handler (${testcase.observedStatus})`
	};
}

// A case the report does not hold an observation for (a partial run, a case that failed before it got an answer)
// says nothing about its handler: rebuilding without it would silently drop its pin. Refuse instead.
const unobserved = [...expected].filter((title) => !observed.has(title));
if (unobserved.length) {
	console.error(
		`the report has no observed status for ${unobserved.length} of ${expected.size} bodiless cases; run the whole API suite first. Missing: ${unobserved.slice(0, 10).join(', ')}${unobserved.length > 10 ? ', …' : ''}`
	);
	process.exit(1);
}

const sorted = Object.fromEntries(Object.entries(blockers).sort(([a], [b]) => a.localeCompare(b)));
const body = `// GENERATED by apps/web/playwright/scripts/collect-empty-body-blockers.mjs — do not hand-edit.
// Rebuild it from a run:
//   yarn playwright test --config apps/web/playwright/playwright.api.config.ts
//   node apps/web/playwright/scripts/collect-empty-body-blockers.mjs
//
// Each entry is a route handler that answered a 5xx to a mutating request carrying no body, pinned
// to the status it produced. suites/api/empty-body.spec.ts asserts each pinned status exactly, so a
// fixed handler fails the run until its entry is removed and a changed one fails on the spot.

export type EmptyBodyBlocker = { status: number; detail: string };

export const emptyBodyBlockers: Record<string, EmptyBodyBlocker> = ${JSON.stringify(sorted, null, 1)};
`;

await writeGenerated(outputFile, body, 'node apps/web/playwright/scripts/collect-empty-body-blockers.mjs');
console.log(`pinned ${Object.keys(sorted).length} handlers that 5xx on a bodiless call`);
console.log(`wrote ${relative(process.cwd(), outputFile)}`);
